"""Record what the server answers for one model, for the viewport's browser tests.

    python tests/make_viewport_fixture.py            # print sizes, write nothing
    python tests/make_viewport_fixture.py --write    # (re)write the fixture

`frontend/js/viewport.js` boots against `/api/project` and `/api/geometry`, meshes through
`/api/mesh`, numbers through `/api/mesh/labels` and colours nodes through
`/api/mesh/node-parts`. Its browser suite (`frontend/tests/test-viewport-live.js`) answers
those requests from this recording instead of a server, so the module can be booted and
driven in the test page.

The model is the test model (`tests/models/excavation.py`, staged) at a coarse mesh:
staged stages, a sheet pile with interfaces both sides, a strut, line loads and a water
level -- most of what the viewport draws -- in a file small enough to commit. Plus one
imported `.mdpa` preview (the coarse deck of the same model), for the imported-mesh half.

Generated, never edited: rerun with --write after a change to any of those payloads.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "frontend" / "tests" / "fixtures" / "viewport-payloads.js"
SETTINGS = {"element_size": 8.0, "order": 1}


def record() -> dict:
    import os

    os.environ.setdefault("KRATOS_GUI_ALLOWED_HOSTS", "testserver")
    from fastapi.testclient import TestClient

    from core.kratos import mdpa_reader, node_parts
    from backend.main import app
    from tests.models import excavation

    with TestClient(app) as client:
        project = excavation.excavation_project(staged=True).model_dump(mode="json")
        assert client.put("/api/project", json=project).status_code == 200
        out = {
            "settings": SETTINGS,
            "project": client.get("/api/project").json(),
            "geometry": client.get("/api/geometry").json(),
            "mesh": client.post("/api/mesh", json=SETTINGS).json(),
            "labels": client.post("/api/mesh/labels", json=SETTINGS).json(),
            "nodeParts": client.post("/api/mesh/node-parts", json=SETTINGS).json(),
        }
        deck = client.post("/api/export/mdpa", json=SETTINGS).json()["mdpa"]
        model = mdpa_reader.import_mdpa(deck)
        out["imported"] = {**model.to_dict(), "node_parts": node_parts.of_model(model)}
        # The same model in 3D -- the wall a panel, the strut a member -- with one drawn
        # box: what the solid model's property grids are built from.
        assert client.patch("/api/project/dimension", json={"dimension": 3}).status_code == 200
        assert client.post("/api/geometry/create", json={
            "kind": "box", "origin": [30, -4, 5], "size": [2, 2, 2], "label": "Block",
        }).status_code == 200
        out["project3d"] = client.get("/api/project").json()
        client.post("/api/project/reset")
    return out


def render(payloads: dict) -> str:
    body = json.dumps(payloads, separators=(",", ":"))
    return ("/* Generated by tests/make_viewport_fixture.py -- do not edit. */\n"
            "window.VIEWPORT_PAYLOADS = " + body + ";\n")


def main(argv: list[str]) -> int:
    payloads = record()
    for key, value in payloads.items():
        print(f"{key:10s} {len(json.dumps(value)) / 1024:8.1f} KB")
    if "--write" in argv:
        OUT.write_text(render(payloads), encoding="utf-8")
        print(f"wrote {OUT} ({OUT.stat().st_size / 1024:.0f} KB)")
    return 0


if __name__ == "__main__":
    sys.path.insert(0, str(ROOT))
    raise SystemExit(main(sys.argv))
