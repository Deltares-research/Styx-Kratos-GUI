"""Record one section of one stage, as the results routes send it, for the JS suites.

    python tests/make_results_field_fixture.py            # print what it would write
    python tests/make_results_field_fixture.py --write    # (re)write the fixture

`frontend/tests/test-results-render.js` is otherwise made of four-vertex squares, which is
the right way to pin an edge case and the wrong way to notice that a whole mesh comes out
grey. This records a whole soil body of the test model (`tests/models/excavation.py`) in
its last stage, with p' at the nodes, p' per element and the vertical displacement, read
through `core.results` exactly as the server answers the page.

The run is synthetic -- `tests/fakes/gid_writer.py` with analytic fields -- so this needs
no Kratos and writes the same file on every machine. The fields are the ones the fake
runner uses, with the stress shifted so that p' is compression everywhere, as in real
ground under its own weight:

    TOTAL_DISPLACEMENT = stage * (1e-3 x, -1e-3 y, 0)
    CAUCHY_STRESS      = (0.6 s, s, 0.6 s), s = 18 kPa/m * y - 5 kPa

Generated, never edited: rerun with --write after a change to any of those payloads.
"""

from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "frontend" / "tests" / "fixtures" / "results-field.js"
RUN = "Staged_excavation_2026-01-01_00-00"
STAGE = 7
SECTION = "results:Soil_Middle_pit"

HEADER = """/* Generated by tests/make_results_field_fixture.py -- do not edit.

   One whole section of one stage, for the arithmetic that decides what gets drawn: %(part)s
   of the test model in stage %(stage)d, %(vertices)d vertices, %(triangles)d triangles, and the
   values that go on them, as the results routes send them. Synthetic values on a real
   mesh: see the generator.

   A .js file assigning a global rather than a .json one, because the browser suite is
   opened from file://, where a fetch is blocked. Same convention as phase-cases.js.
*/
window.RESULTS_FIELD =
"""


def u(x, y, z, stage):
    return (stage * 1e-3 * x, -stage * 1e-3 * y, 0.0)


def stress(x, y, z, stage):
    s = 18000.0 * y - 5000.0
    return (0.6 * s, s, 0.6 * s, 0.0, 0.0, 0.0)


def round_all(value, digits: int = 6):
    """Floats to a fixed number of decimals, recursively, so the file reads and diffs."""
    if isinstance(value, float):
        return round(value, digits)
    if isinstance(value, list):
        return [round_all(item, digits) for item in value]
    if isinstance(value, dict):
        return {key: round_all(item, digits) for key, item in value.items()}
    return value


def compact_json(payload: dict, depth: int = 2, indent: int = 1) -> str:
    """Two levels of keys expanded and everything below them compact, so the file opens
    on a shape rather than on a column of integers."""
    if depth == 0 or not isinstance(payload, dict):
        return json.dumps(payload, separators=(",", ":"))
    pad = " " * indent
    lines = [f"{pad}{json.dumps(key)}: {compact_json(value, depth - 1, indent + 1)}"
             for key, value in payload.items()]
    return "{\n" + ",\n".join(lines) + "\n" + " " * (indent - 1) + "}"


def record() -> dict:
    import os

    from core import calculate, kratos, results
    from tests.fakes import gid_writer
    from tests.models import excavation

    export = kratos.export_project(excavation.excavation_project(staged=True))
    with tempfile.TemporaryDirectory(prefix="results-field-") as root:
        gid_writer.write_run(export, Path(root) / RUN, nodal={"TOTAL_DISPLACEMENT": u},
                             gauss={"CAUCHY_STRESS_TENSOR": stress})
        os.environ[calculate.RUNS_ENV] = root
        results.forget_cache()
        try:
            sections = results.stage_geometry(RUN, STAGE)["sections"]
            section = next(one for one in sections if one["key"] == SECTION)
            wanted = {"nodes": set(section["node_ids"]),
                      # The ids the triangles were built from, not the part's own list.
                      "elements": set(section["triangle_elements"])}

            def field(name: str, location: str) -> dict:
                """One field, cut down to the ids this section draws. `min` and `max` stay
                the whole stage's: the legend is drawn for the stage."""
                found = results.stage_field(RUN, STAGE, name, location)
                kept = [(id, value) for id, value in zip(found["ids"], found["values"])
                        if id in wanted[location]]
                return found | {"ids": [id for id, _ in kept],
                                "values": [value for _, value in kept]}

            return {"run": RUN, "stage": STAGE, "section": section,
                    "fields": {"p_nodes": field("p", "nodes"),
                               "p_elements": field("p", "elements"),
                               "uy": field("uy", "nodes")}}
        finally:
            results.forget_cache()


def render(payload: dict) -> str:
    section = payload["section"]
    header = HEADER % {"part": section["part"], "stage": payload["stage"],
                       "vertices": len(section["node_ids"]),
                       "triangles": len(section["indices"]) // 3}
    return header + compact_json(round_all(payload)) + ";\n"


def main(argv: list[str]) -> int:
    text = render(record())
    print(f"{OUT.name}: {len(text) / 1024:.0f} KB")
    if "--write" in argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.path.insert(0, str(ROOT))
    raise SystemExit(main(sys.argv))
